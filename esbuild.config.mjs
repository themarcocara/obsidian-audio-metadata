import esbuild from "esbuild";
import process from "process";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
source: https://github.com/  (audio-tags plugin)
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  // Only obsidian is external. Node builtins must NOT be marked external: this
  // bundle runs in Obsidian's WebView on Android, where require()/node:fs do not exist.
  external: ["obsidian"],
  outfile: "main.js",
  format: "cjs",
  platform: "browser",
  // es2018 matches Obsidian's own sample plugin. es2020+ leaves ?. and ?? in the
  // output, which are parse errors on Android WebView < Chrome 80 (many Android
  // 7-9 devices) and make the whole plugin fail to load.
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  minify: prod,
});

if (prod) {
  await context.rebuild();
  await context.dispose();
  process.exit(0);
} else {
  await context.watch();
}
